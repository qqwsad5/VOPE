import json
import os
import shutil
from tqdm import tqdm
from time import sleep
import base64
import openai

# ===================== Path Configuration (Please fill in actual paths) =====================
# Path to the MSCOCO val2014 image folder
data_root = "../data/val2014"
# Root directory for saving GPT evaluation results
save_root = "../results"
# ============================================================================================

def encode_image(image_path):
    """Encode an image file to a base64 string."""
    with open(image_path, "rb") as image_file:
        return base64.b64encode(image_file.read()).decode('utf-8')

# OpenAI API key (please fill in your actual key)
client = openai.OpenAI(api_key="put your openai key here")

def gpt_evaluate(img_path, text):
    """
    Call GPT-4o to score the relevance between an object and the image.
    Retries once on failure; returns an empty string if the retry also fails.
    """
    num = 0
    answer = None
    while answer is None:
        if num == 1:
            # Return empty string after one failed retry
            answer = ""
            break
        try:
            num += 1
            base64_image = encode_image(img_path)
            response = client.chat.completions.create(
                model="gpt-4o",
                messages=[
                    {"role": "user", "content": [
                        {"type": "text", "text": text},
                        {"type": "image_url", "image_url": {
                            "url": f"data:image/jpg;base64,{base64_image}"}
                        }
                    ]}
                ],
                max_tokens=200,
                temperature=1.0
            )
            answer = response.choices[0].message.content

        except Exception as e:
            print('Error', e)
            sleep(2)

    return answer

# List of datasets to evaluate
dataset_list = [
    'generative_captioning'
]

# List of models to evaluate
model_name_list = [
    'llava',
    'qwen3'
]

# Load the relevance scoring prompt template
with open(os.path.join(os.path.dirname(__file__), "prompt.txt"), 'r') as file:
    prompt = file.read()

for dataset in dataset_list:
    for model_name in model_name_list:
        print("Evaluating: Model {}, Dataset {}".format(model_name, dataset))

        save_folder_path = os.path.join(save_root, "gpt_eval_{}".format(dataset))
        os.makedirs(save_folder_path, exist_ok=True)
        save_file_path = os.path.join(save_folder_path, "{}_results.json".format(model_name))

        # If the output file already exists, keep a backup and resume writing from it;
        # otherwise load from the label file generated by gen_eval_label.py
        source_file_path = os.path.join(os.path.dirname(__file__), dataset, "{}.json".format(model_name))
        if os.path.exists(save_file_path):
            shutil.copy(save_file_path, save_file_path.replace('.json', '_copy.json'))
            with open(save_file_path, 'r') as file:
                info_list = json.load(file)
        else:
            with open(source_file_path, 'r') as file:
                info_list = json.load(file)

        fail_count = 0
        for info in tqdm(info_list):
            # Skip entries that already have a non-empty gpt_answer (supports resuming)
            if 'gpt_answer' in info and len(info['gpt_answer']) != 0:
                continue

            # Build image path and call GPT for relevance scoring
            img_path = os.path.join(data_root, info['images'][0])
            output = gpt_evaluate(img_path, prompt.format(info['target']))
            info['gpt_answer'] = output

            # Stop evaluating the current model and save completed results if
            # consecutive failures exceed the threshold
            if len(output) == 0:
                fail_count += 1
            else:
                fail_count = 0
            if fail_count == 30:
                break

        # Write results to file
        with open(save_file_path, 'w', encoding='utf-8') as file:
            json.dump(info_list, file, indent=4)

        # Remove the backup file
        if os.path.exists(save_file_path.replace('.json', '_copy.json')):
            os.remove(save_file_path.replace('.json', '_copy.json'))
